def step_of(key):
    """The main.py step whose results provide a number of the manuscript."""
    if key.startswith("Bench"):
        return "benchmark"
    if key.startswith("ScreenBench"):
        return "screening (registry graphs)"
    if key.startswith("Screen"):
        return "screening (large networks)"
    if key.startswith("Map"):
        return "screening_map"
    return "bounds"


def find_manuscript(paper_dir, manuscript=None):
    if manuscript:
        p = manuscript if os.path.isabs(manuscript) else os.path.join(paper_dir, manuscript)
        return p if os.path.exists(p) else None
    p = os.path.join(paper_dir, "manuscript.tex")
    if os.path.exists(p):
        return p
    cands = [f for f in sorted(glob.glob(os.path.join(paper_dir, "*.tex")))
             if "\\documentclass" in open(f, encoding="utf-8", errors="ignore").read()]
    return max(cands, key=os.path.getmtime) if cands else None


def manuscript_keys(path):
    """The \\res and \\resrows keys used by a manuscript, in order of appearance."""
    s = open(path, encoding="utf-8", errors="ignore").read()
    s = re.sub(r"(?<!\\)%[^\n]*", "", s)  # drop comments
    res = list(dict.fromkeys(re.findall(r"\\res\{([^}]*)\}", s)))
    rows = list(dict.fromkeys(re.findall(r"\\resrows\{([^}]*)\}", s)))
    return res, rows


def copy_figures(results_dir, paper_dir):
    src = os.path.join(results_dir, "figures")
    dst = os.path.join(paper_dir, "figures_paper")
    if not os.path.isdir(src):
        return []
    os.makedirs(dst, exist_ok=True)
    out = []
    for f in sorted(os.listdir(src)):
        if os.path.isfile(os.path.join(src, f)):
            shutil.copy2(os.path.join(src, f), os.path.join(dst, f))
            out.append(f)
    return out


def build(results_dir, paper_dir, manuscript=None):
    """Write <paper>/generated/ and <paper>/figures_paper/. Returns a summary dict:
    tables (label -> status), numbers (count), manuscript (path or None),
    missing (manuscript keys without a value), missing_rows, figures (copied files)."""
    from curvature_transfer import _io

    gen = os.path.join(paper_dir, "generated")
    os.makedirs(gen, exist_ok=True)
    N = Numbers()
    rows, status = {}, {}
    p = os.path.join(results_dir, "tables", "bounds", "bound_comparison.csv")
    if os.path.exists(p):
        rows.update(bounds_numbers(N, read_csv(p), os.path.relpath(p, results_dir)))
    sdir = os.path.join(results_dir, "tables", "screening")
    p = os.path.join(sdir, "screening_benchmark.csv")
    if os.path.exists(p):
        screening_benchmark_numbers(N, read_csv(p), os.path.relpath(p, results_dir))
    p = os.path.join(sdir, "screening_large.csv")
    if os.path.exists(p):
        txt = screening_large_numbers(N, read_csv(p), os.path.relpath(p, results_dir))
        if txt:
            rows["screening"] = txt
    p = os.path.join(results_dir, "screening_map", "screening_map_numbers.tex")
    if os.path.exists(p):
        screening_map_numbers(N, p, os.path.relpath(p, results_dir))
    bdir = os.path.join(results_dir, "benchmark")
    if os.path.isdir(bdir):
        by_family = {}
        for fam, p in sorted(benchmark_files(bdir).items()):
            brows = read_csv(p)
            if brows:
                by_family[fam] = brows
                benchmark_numbers(N, brows, os.path.relpath(p, results_dir), "" if fam == "ER" else f":{fam}")
        if by_family:
            for lab in ("Sharp", "BF"):
                lo_, hi_ = [], []
                for fam in by_family:
                    S = "" if fam == "ER" else f":{fam}"
                    for k, acc in ((f"BenchRatio{lab}Min{S}", lo_), (f"BenchRatio{lab}Max{S}", hi_)):
                        try:
                            acc.append(float(N.get(k)))
                        except (TypeError, ValueError):
                            pass
                if lo_ and hi_:
                    fmt = lambda x: f"{x:.0f}" if x >= 10 else f"{x:.1f}"
                    N.add(f"BenchRatio{lab}MinAll", fmt(min(lo_)), "Abstract; Section 6.4 (all families)",
                          "benchmark/benchmark_<family>_*.csv")
                    N.add(f"BenchRatio{lab}MaxAll", fmt(max(hi_)), "Abstract; Section 6.4 (all families)",
                          "benchmark/benchmark_<family>_*.csv")
            rt = runtime_artifacts(N, by_family, "benchmark/benchmark_<family>_*.csv")
            if rt:
                rows["runtime"] = rt
    allrows = {}
    for lab, ncols, where, step in TABLES:
        txt = rows.get(lab)
        status[lab] = "generated" if txt else f"MISSING (run step '{step}')"
        key = lab.replace("_", "-")
        allrows[key] = txt or pending_rows(ncols, lab.replace("_", "\\_"))
        _io.atomic_text(allrows[key], os.path.join(gen, f"rows-{key}.tex"))
    _io.atomic_text(N.tex(allrows), os.path.join(gen, "numbers.tex"))
    cons = os.path.join(results_dir, "CONSISTENCY.md")
    if os.path.exists(cons):
        shutil.copy2(cons, os.path.join(gen, "CONSISTENCY.md"))
    figures = copy_figures(results_dir, paper_dir)
    man = find_manuscript(paper_dir, manuscript)
    missing, missing_rows = [], []
    if man:
        res_keys, rows_keys = manuscript_keys(man)
        missing = [k for k in res_keys if N.get(k) is None]
        missing_rows = [k for k in rows_keys if k not in allrows or status.get(k.replace("-", "_"), status.get(k)) != "generated"]
    L = ["# What goes where", "",
         "Everything in this folder is generated by `python main.py` (step `paper`); nothing here is edited by hand.",
         "The manuscript reads `numbers.tex`, which holds every number and every table body; the `rows-*.tex`",
         "files are the same table bodies, one file per table, for reading. A number that has not been generated",
         "is printed in red as `[Key]` in the PDF. Cross-checks: `CONSISTENCY.md` (step `consistency`).", ""]
    if man:
        L += [f"Manuscript: `{os.path.relpath(man, paper_dir)}` uses {len(res_keys)} numbers and {len(rows_keys)} tables; "
              f"{len(res_keys) - len(missing)} numbers and {len(rows_keys) - len(missing_rows)} tables are available.", ""]
    else:
        L += ["No manuscript found in the paper directory, so the keys it uses were not checked.", ""]
    if missing or missing_rows:
        L += ["## Missing (printed in red in the PDF)", "", "| Key | Produced by step |", "| --- | --- |"]
        L += [f"| `{k}` | {step_of(k)} |" for k in missing]
        L += [f"| table `{k}` | see the table list below |" for k in missing_rows]
        L.append("")
    L += ["## Tables (body rows; captions and headers are in the manuscript)", "",
          "| Table in the paper | LaTeX label | File | Status |", "| --- | --- | --- | --- |"]
    for lab, _, where, _ in TABLES:
        L.append(f"| {where} | `tab:{lab}` | `rows-{lab.replace('_', '-')}.tex` | {status[lab]} |")
    L += ["", "## Numbers in the text (`numbers.tex`, used as `\\res{Key}`)", "",
          "| Key | Value | Where it appears | Computed from (under results/) |", "| --- | --- | --- | --- |"]
    for k, (v, where, src) in N.vals.items():
        L.append(f"| `{k}` | {v} | {where} | `{src}` |")
    L += ["", "## Figures", "",
          f"{len(figures)} files copied from `results/figures/` to `../figures_paper/`, the names the manuscript includes."]
    _io.atomic_text("\n".join(L) + "\n", os.path.join(gen, "INDEX.md"))
    return {"tables": status, "numbers": len(N.vals), "manuscript": man, "missing": missing,
            "missing_rows": missing_rows, "figures": figures}


