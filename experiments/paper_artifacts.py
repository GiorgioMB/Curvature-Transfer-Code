def gnn_rows(N, res, cfg, src):
    def fmt_score(x, s, metric):
        if metric == "mae":
            return f"{x:.3f} $\\pm$ {s:.3f}"
        return f"{100 * x:.1f} $\\pm$ {100 * s:.1f}"

    down, conn = [], []
    archs = cfg.get("archs", ["GCN", "GIN", "GAT"])
    for ds, name, metric in GNN_DATASETS:
        block = []
        for a, arch in enumerate(archs):
            entry = res.get(f"{ds}_{arch}", {})
            vals = [(entry.get(p, {}).get("avg"), entry.get(p, {}).get("std")) for p, _ in GNN_PIPES]
            have = [v for v in vals if v[0] is not None]
            if not have:
                cells = [f"\\multicolumn{{{len(GNN_PIPES)}}}{{c}}{{\\pending{{not run}}}}"]
            else:
                txt = [fmt_score(v[0], v[1] or 0.0, metric) if v[0] is not None else "--" for v in vals]
                best = (min if metric == "mae" else max)(v[0] for v in have)
                key = lambda x: fmt_score(x, 0, metric).split(" ")[0]
                cells = [f"\\textbf{{{t}}}" if v[0] is not None and key(v[0]) == key(best) else t for t, v in zip(txt, vals)]
            lead = f"\\multirow{{{len(archs)}}}{{*}}{{\\texttt{{{name}}}}}" if a == 0 else ""
            block.append(f"{lead} & {arch} & " + " & ".join(cells) + " \\\\")
        down.append("\n".join(block))
        # connectivity: one topology per pipeline (identical across architectures); time averaged over architectures
        rows = []
        for p, pname in GNN_PIPES:
            ents = [res.get(f"{ds}_{arch}", {}).get(p) for arch in archs]
            ents = [e for e in ents if e]
            if not ents:
                continue
            t = np.mean([e.get("rewire_time") or 0.0 for e in ents])
            topo = ents[0].get("topology") or {}
            fied = topo.get("Fiedler", float("nan"))
            e10 = int(math.floor(math.log10(abs(fied)))) if fied and fied > 0 else 0
            fstr = f"${fied / 10 ** e10:.2f} \\times 10^{{{e10}}}$" if fied and fied > 0 else "--"
            rows.append([pname, "--" if p == "Original" else f"{t:.1f}", f"{topo.get('Diameter', float('nan')):.2f}",
                         f"{topo.get('Avg_SP', float('nan')):.2f}", fstr])
        if not rows:
            conn.append(f"\\texttt{{{name}}} & \\multicolumn{{5}}{{c}}{{\\pending{{not run}}}} \\\\")
        else:
            times = [float(r[1]) for r in rows if r[1] != "--"]
            tbest = f"{min(times):.1f}" if times else None
            out = []
            for k, r in enumerate(rows):
                if r[1] == tbest:
                    r[1] = f"\\textbf{{{r[1]}}}"
                lead = f"\\multirow{{{len(rows)}}}{{*}}{{\\texttt{{{name}}}}}" if k == 0 else ""
                out.append(f"{lead} & " + " & ".join(r) + " \\\\")
            conn.append("\n".join(out))
    # ---- non-inferiority tests (same procedure as stats.py)
    import stats as st
    tests, pv = [], []
    delta = cfg.get("delta")
    pairs = [("BORF (Bounds)", "BORF (OR)", "S-BORF vs BORF"), ("BORF (Sharpened)", "BORF (OR)", "S$^{+}$-BORF vs BORF"),
             ("SDRF (Bounds)", "SDRF (OR)", "S-SDRF vs OR-SDRF"), ("BORF (JL)", "BORF (OR)", "JL-BORF vs BORF")]
    if delta is not None:
        for ds, name, metric in GNN_DATASETS:
            for arch in archs:
                entry = res.get(f"{ds}_{arch}", {})
                for sur, ref, lab in pairs:
                    if sur in entry and ref in entry:
                        try:
                            d, K, _ = st.fold_differences(entry[sur], entry[ref], metric != "mae")
                        except ValueError:
                            continue
                        p, m, lcb = st.noninferiority(d, K, float(delta))
                        if math.isfinite(p):
                            tests.append([name, arch, lab, m, lcb, sur]); pv.append(p)
    tests_rows = []
    if tests:
        adj = st.holm(pv)
        for t, pa in zip(tests, adj):
            t.append(pa)
        for sur, ref, lab in pairs:
            sel = [t for t in tests if t[5] == sur]
            key = {"BORF (Bounds)": "SBORF", "BORF (Sharpened)": "SplusBORF", "SDRF (Bounds)": "SSDRF", "BORF (JL)": "JLBORF"}[sur]
            N.add(f"NonInf{key}", sum(t[6] < 0.05 for t in sel), "Appendix A (Results)", src)
            N.add(f"NonInfTotal{key}", len(sel), "Appendix A (Results)", src)
        for name, arch, lab, m, lcb, sur, pa in tests:
            v = "non-inferior" if pa < 0.05 else "not shown"
            tests_rows.append(f"\\texttt{{{name}}} & {arch} & {lab} & {m:+.4f} & {lcb:+.4f} & {pa:.3f} & {v} \\\\")
    ratios = []
    for ds, name, metric in GNN_DATASETS:
        for sur, key in (("BORF (Bounds)", "SBORF"), ("SDRF (Bounds)", "SSDRF")):
            ref = {"BORF (Bounds)": "BORF (OR)", "SDRF (Bounds)": "SDRF (OR)"}[sur]
            ts = [(res.get(f"{ds}_{a}", {}).get(sur, {}).get("rewire_time"), res.get(f"{ds}_{a}", {}).get(ref, {}).get("rewire_time")) for a in archs]
            ts = [(x, y) for x, y in ts if x and y]
            if ts:
                ratios.append((key, np.mean([y for _, y in ts]) / np.mean([x for x, _ in ts])))
    for key in ("SBORF", "SSDRF"):
        r = [v for k, v in ratios if k == key]
        if r:
            N.add(f"TimeRatio{key}Min", f"{min(r):.1f}", "Appendix A (Results)", src)
            N.add(f"TimeRatio{key}Max", f"{max(r):.1f}", "Appendix A (Results)", src)
    mi = cfg.get("max_iters_rewiring", {})
    if mi:
        N.add("GnnMaxItersMinesweeper", mi.get("minesweeper"), "Appendix A", src)
        N.add("GnnMaxItersOther", mi.get("other"), "Appendix A", src)
    for k in ("reps", "cv_split", "trials", "epochs"):
        if k in cfg:
            N.add({"reps": "GnnReps", "cv_split": "GnnK", "trials": "GnnTrials", "epochs": "GnnEpochs"}[k], cfg[k], "Appendix A", src)
    if cfg.get("delta") is not None:
        N.add("GnnDelta", cfg["delta"], "Appendix A", src)
    return ("\n\\midrule\n".join(down) + "\n", "\n\\midrule\n".join(conn) + "\n",
            ("\n".join(tests_rows) + "\n") if tests_rows else None)


