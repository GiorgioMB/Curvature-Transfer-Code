def disp(name):
    s = suite.BY_NAME.get(name)
    return s.display if s else name


def join(items):
    items = list(items)
    if not items:
        return "none"
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + (", and " if len(items) > 2 else " and ") + items[-1]


def thou(x):
    return f"{int(x):,}".replace(",", "{,}")


class Numbers:
    def __init__(self):
        self.vals = OrderedDict()

    def add(self, key, value, where, source):
        self.vals[key] = (str(value), where, source)

    def get(self, key):
        return self.vals[key][0] if key in self.vals else None

    def tex(self, rows=None):
        out = ["% Generated by experiments/paper_artifacts.py -- do not edit by hand.",
               "% \\res{Key} prints a number; \\resrows{key} the body rows of a table."]
        for k, (v, _, _) in self.vals.items():
            out.append(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}")
        for k, txt in (rows or {}).items():
            out.append(f"\\expandafter\\def\\csname resrows@{k}\\endcsname{{%\n{txt.rstrip()}\n}}")
        return "\n".join(out) + "\n"


def fin(x):
    return x is not None and isinstance(x, (int, float)) and math.isfinite(x)


def pct(x):
    return f"{100 * x:.1f}" if fin(x) else "--"


def read_csv(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def num(r, k):
    try:
        return float(r[k])
    except (KeyError, ValueError, TypeError):
        return float("nan")


def parse_bounds(rows):
    R = []
    for r in rows:
        o = {}
        for k, v in r.items():
            o[k] = v if k in ("graph", "tag", "group") else num(r, k)
        o["E"] = int(o["E"])
        R.append(o)
    return R


def agg(R):
    return [o for o in R if o["group"] in suite.AGGREGATE_GROUPS]


def _range(N, R, k, label, where, src, with_graphs=True):
    """Min/max over graphs of a per-graph fraction k (NaN skipped) + graph names at the extremes."""
    vals = [(o[k], o) for o in R if fin(o.get(k))]
    if not vals:
        return
    lo, hi = min(v for v, _ in vals), max(v for v, _ in vals)
    N.add(f"{label}Min", pct(lo), where, src)
    N.add(f"{label}Max", pct(hi), where, src)
    if with_graphs:
        N.add(f"{label}MinGraphs", join(disp(o["graph"]) for v, o in vals if pct(v) == pct(lo)), where, src)
        N.add(f"{label}MaxGraphs", join(disp(o["graph"]) for v, o in vals if pct(v) == pct(hi)), where, src)


