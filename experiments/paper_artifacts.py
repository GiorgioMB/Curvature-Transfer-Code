#!/usr/bin/env python3
"""Turn the results of main.py into the files the manuscript reads (step ``paper``).

Writes, into ``<paper>/generated/``:

  numbers.tex      one macro per number of the text, read by \\res{Key}, and the body rows of
                   every generated table, read by \\resrows{label}
  rows-<label>.tex the same table bodies, one file per table, for reading
  INDEX.md         every table and number: its value, where it appears, and the file it is computed
                   from; plus the keys the manuscript uses that the results do not provide yet
  CONSISTENCY.md   copy of ``results/CONSISTENCY.md`` (step ``consistency``, :func:`consistency_checks`)

and copies ``results/figures/*`` to ``<paper>/figures_paper/``, from which the manuscript includes
its figures.

Single sources. Every number comes from one raw file: Tables 3-6 and the numbers of Sections
6.1-6.2 and Appendix C from ``tables/bounds/bound_comparison.csv``; Section 6.3 from
``tables/screening/screening_benchmark.csv`` (registry graphs, stored intervals),
``tables/screening/screening_large.csv`` (Table 7, timed) and the edge map
(``screening_map/screening_map_numbers.tex``); Section 6.4 and Table 8 from
``benchmark/benchmark_<family>_*.csv``. The bound and screening files are computed from the same
per-edge arrays (``results/edges``). Aggregates over graphs (ranges, medians, "on k of the N
graphs") use ``suite.AGGREGATE_GROUPS``; undefined per-graph values print as "--" and are skipped.

Usage: python paper_artifacts.py --results ../results --paper ../results/paper [--manuscript FILE]
"""
