def benchmark_numbers(N, rows, src, suffix=""):
    """Numbers of Section 6.4 for one family (``suffix`` "" for ER, ":BA" etc. otherwise).
    Phases that were not run at some sizes (see benchmark.py) are skipped by the
    ratios; ``BenchLastN<phase>`` is the largest size at which a phase was measured."""
    n = np.array([int(r["n"]) for r in rows])
    o = np.argsort(n)
    n = n[o]
    col = lambda k: np.array([num(r, k) for r in rows])[o]
    ex, sh, mt, bf = col("exact_s"), col("sharpened_interval_s"), col("matching_interval_s"), col("bf_interval_s")
    m = np.array([int(r["num_edges"]) for r in rows])[o]
    S = suffix
    N.add(f"BenchMinN{S}", int(n.min()), "Section 6.4", src)
    N.add(f"BenchMaxN{S}", int(n.max()), "Section 6.4", src)
    N.add(f"BenchNumGraphs{S}", len(n), "Section 6.4", src)
    N.add(f"BenchMaxEdges{S}", thou(m[-1]), "Section 6.4", src)
    N.add(f"BenchThreads{S}", rows[0]["threads"], "Section 6.4", src)
    t = int(float(rows[0]["threads"]))
    N.add(f"BenchThreadsText{S}", f"{t} thread" + ("" if t == 1 else "s"), "Section 6.4", src)
    ch = [int(r["n"]) for r in rows if str(r.get("chunked")) in ("True", "true", "1")]
    N.add(f"BenchChunkedFromN{S}", min(ch) if ch else "none", "Section 6.4 (chunked timing from this n on)", src)
    fmt = lambda x: f"{x:.0f}" if x >= 10 else f"{x:.1f}"
    for key, y in (("Exact", ex), ("Sharp", sh), ("Match", mt), ("BF", bf)):
        ok = np.isfinite(y)
        N.add(f"BenchLastN{key}{S}", int(n[ok][-1]) if ok.any() else "none", "Section 6.4 (largest n measured)", src)
        if ok.any():
            N.add(f"Bench{key}AtLastN{S}", fmt(y[ok][-1]), "Section 6.4 (seconds at that n)", src)
    both = np.isfinite(ex) & np.isfinite(sh)
    N.add(f"BenchBothLastN{S}", int(n[both][-1]) if both.any() else "--", "Section 6.4 (largest n with exact and sharpened measured)", src)
    N.add(f"BenchExactAtMax{S}", fmt(ex[both][-1]) if both.any() else "--", "Section 6.4", src)
    N.add(f"BenchSharpAtMax{S}", fmt(sh[both][-1]) if both.any() else "--", "Section 6.4", src)
    N.add(f"BenchBFAtMax{S}", fmt(bf[both][-1]) if both.any() else "--", "Section 6.4", src)
    big = n >= 1000  # ratios over the range where timings are not dominated by overhead
    sel = big if big.any() else np.ones_like(big)
    for lab, den in (("Sharp", sh), ("Match", mt), ("BF", bf)):
        r = (ex / den)[sel]
        r = r[np.isfinite(r)]
        N.add(f"BenchRatio{lab}Min{S}", fmt(r.min()) if len(r) else "--", "Section 6.4", src)
        N.add(f"BenchRatio{lab}Max{S}", fmt(r.max()) if len(r) else "--", "Section 6.4", src)
        lo_, hi_ = (fmt(r.min()), fmt(r.max())) if len(r) else ("--", "--")
        N.add(f"BenchRatio{lab}Range{S}", lo_ if lo_ == hi_ else f"{lo_}--{hi_}", "Section 6.4", src)
    N.add(f"BenchRatioFromN{S}", int(n[sel][0]), "Section 6.4", src)
    skipped = sorted({str(r.get(f"{ph}_status")) for r in rows for ph in ("exact", "matching_interval", "sharpened_interval")
                      if str(r.get(f"{ph}_status", "")).startswith("skipped (") and "not run from" not in str(r.get(f"{ph}_status"))})
    N.add(f"BenchSkipReasons{S}", "; ".join(skipped) if skipped else "none", "Section 6.4 (why phases stop)", src)


BENCH_FAMILIES = [("ER", "ER"), ("BA", "BA"), ("RGG", "RGG"), ("WS", "WS")]
BENCH_PHASES = [("exact", "exact evaluation"), ("matching_interval", "the matching interval"),
                ("sharpened_interval", "the sharpened interval")]
RUNTIME_NCOLS = 9


def _skip_kind(status, budget_hours):
    s = str(status)
    if s.startswith("skipped (predicted"):
        return f"extrapolated time above the budget of {budget_hours:g} hours per size"
    if s.startswith("skipped (memory"):
        return "estimated memory above the allocation"
    if s.startswith("skipped (killed"):
        return "the same chunk killed twice"
    return "not run"


def runtime_artifacts(N, by_family, src_of):
    """Table rows of tab:runtime (Table 8) and the generated sentences of Section 6.4."""
    rows_tex, stops, chunk_from = [], [], []
    chunk_above = chunk = None
    for fam, name in BENCH_FAMILIES:
        rows = by_family.get(fam)
        if not rows:
            continue
        rows = sorted(rows, key=lambda r: int(r["n"]))
        n = np.array([int(r["n"]) for r in rows])
        col = lambda k: np.array([num(r, k) for r in rows])
        ex, sh, bf = col("exact_s"), col("sharpened_interval_s"), col("bf_interval_s")
        last = rows[-1]
        okx = np.isfinite(ex)
        exact_upto = f"{int(n[okx][-1])}" if okx.any() else "--"
        sel = n >= 1000 if (n >= 1000).any() else np.ones(len(n), bool)

        def rng(r):
            if not np.isfinite(r).any():
                return "--"
            lo, hi = _sci(np.nanmin(r)), _sci(np.nanmax(r))
            return lo if lo == hi else f"{lo}--{hi}"
        rs, rb = (ex / sh)[sel], (ex / bf)[sel]
        rows_tex.append(f"{name} & {int(n[-1])} & {int(last['num_edges']):,} & {exact_upto} & {rng(rs)} & {rng(rb)} & "
                        f"{_sci(bf[-1])} & {_sci(sh[-1])} & {_sci(ex[-1])} \\\\".replace(",", "{,}"))
        groups = OrderedDict()  # (first n not run, reason) -> phases
        for ph, phname in BENCH_PHASES:
            sk = [r for r in rows if str(r.get(f"{ph}_status", "")).startswith("skipped (") and
                  "not run from" not in str(r.get(f"{ph}_status"))]
            if sk:
                key = (int(sk[0]["n"]), _skip_kind(sk[0][f"{ph}_status"], num(sk[0], "budget_hours")))
                groups.setdefault(key, []).append(phname)
        if groups:
            kinds = {kind for (_, kind) in groups}
            one = len(kinds) == 1
            cl = [f"{join(ph)} {'was' if len(ph) == 1 else 'were'} not run from $n={nn}$ on" + ("" if one else f" ({kind})")
                  for (nn, kind), ph in sorted(groups.items())]
            stops.append(f"In {name}, " + (", and ".join(cl) if len(cl) <= 2 else "; ".join(cl))
                         + (f" ({next(iter(kinds))})." if one else "."))
        ch = [int(r["n"]) for r in rows if str(r.get("chunked")) in ("True", "true", "1")]
        if ch:
            chunk_from.append(f"$n={min(ch)}$ in {name}")
            chunk_above = chunk_above or num(rows[0], "chunk_above")
            chunk = chunk or num([r for r in rows if int(r["n"]) == min(ch)][0], "chunk")
    if stops:
        N.add("BenchStopSentence", " ".join(stops), "Section 6.4", src_of)
    else:
        N.add("BenchStopSentence", "Every phase was measured at every size in all families.", "Section 6.4", src_of)
    if chunk_from:
        N.add("BenchChunkSentence",
              f"Graphs with more than ${thou(chunk_above)}$ edges (from {join(chunk_from)}) are timed as the sum of the "
              f"times of consecutive chunks of ${thou(chunk)}$ edges, each run once, so that a long run can be resumed "
              "after an interruption; smaller graphs are timed by the median of repeated runs on all edges.",
              "Section 6.4", src_of)
    else:
        N.add("BenchChunkSentence", "Every time is the median of repeated runs on all edges.", "Section 6.4", src_of)
    return "\n".join(rows_tex) + "\n" if rows_tex else None


def benchmark_files(bdir):
    """{family: CSV with the largest max n} among benchmark_<family>_<min>_<max>.csv."""
    out = {}
    for f in os.listdir(bdir):
        if f.startswith("benchmark_") and f.endswith(".csv"):
            parts = f[:-4].split("_")
            if len(parts) == 4 and parts[3].isdigit():
                fam, mx = parts[1], int(parts[3])
                if fam not in out or mx > out[fam][0]:
                    out[fam] = (mx, os.path.join(bdir, f))
    return {k: v[1] for k, v in out.items()}


