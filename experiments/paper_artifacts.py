# ----------------------------------------------------------- screening
def screening_numbers(N, rows, src):
    by = OrderedDict()
    for r in rows:
        by.setdefault(r["graph"], {})[(r["interval"], r["query"].startswith("sign"))] = r
    lines = []
    for gname, d in by.items():
        cells = []
        for q in (True, False):
            vals = [100 * num(d[(iv, q)], "frac_avoided") for iv in ("bf", "matching", "sharpened")]
            b = max(f"{v:.1f}" for v in vals)
            cells += [f"\\textbf{{{v:.1f}}}" if f"{v:.1f}" == b else f"{v:.1f}" for v in vals]
        sp = num(d[("sharpened", True)], "speedup")
        lines.append(f"{gname} & {d[('bf', True)]['E']} & " + " & ".join(cells) + f" & {sp:.1f} \\\\")
    for iv, name in (("bf", "BF"), ("matching", "Matching"), ("sharpened", "Sharpened")):
        for q, qn in ((True, "Sign"), (False, "Bottom")):
            v = [(100 * num(d[(iv, q)], "frac_avoided"), g) for g, d in by.items()]
            lo, hi = min(v), max(v)
            N.add(f"Avoid{qn}{name}Min", f"{lo[0]:.1f}", "Section 7.3", src)
            N.add(f"Avoid{qn}{name}Max", f"{hi[0]:.1f}", "Section 7.3", src)
            N.add(f"Avoid{qn}{name}MinGraph", disp(lo[1]), "Section 7.3", src)
            N.add(f"Avoid{qn}{name}MaxGraph", disp(hi[1]), "Section 7.3", src)
    sp = [(num(d[("sharpened", True)], "speedup"), g, int(d[("sharpened", True)]["E"])) for g, d in by.items()]
    N.add("ScreenSpeedupMax", f"{max(sp)[0]:.1f}", "Section 7.3", src)
    N.add("ScreenSpeedupMaxGraph", disp(max(sp)[1]), "Section 7.3", src)
    N.add("ScreenSpeedupBelowOneList", join(disp(g) for s, g, _ in sp if s < 1.0), "Section 7.3", src)
    N.add("ScreenAllCorrect", "all" if all(r["correct"] in ("True", True) for r in rows) else "NOT all", "Section 7.3", src)
    return "\n".join(lines) + "\n"


# ----------------------------------------------------------- benchmark
def benchmark_numbers(N, rows, src):
    n = np.array([int(r["n"]) for r in rows])
    o = np.argsort(n)
    ex = np.array([num(r, "exact_s") for r in rows])[o]
    sh = np.array([num(r, "sharpened_s") for r in rows])[o]
    bf = np.array([num(r, "bf_interval_s") for r in rows])[o]
    m = np.array([int(r["num_edges"]) for r in rows])[o]
    N.add("BenchMinN", int(n.min()), "Section 7.4", src)
    N.add("BenchMaxN", int(n.max()), "Section 7.4", src)
    N.add("BenchNumGraphs", len(n), "Section 7.4", src)
    N.add("BenchMaxEdges", f"{m[-1]:,}".replace(",", "{,}"), "Section 7.4", src)
    N.add("BenchThreads", rows[0]["threads"], "Section 7.4", src)
    N.add("BenchExactAtMax", f"{ex[-1]:.0f}", "Section 7.4", src)
    N.add("BenchSharpAtMax", f"{sh[-1]:.1f}", "Section 7.4", src)
    big = n[o] >= 1000  # ratios over the range where timings are not dominated by overhead
    r_s = ex[big] / sh[big] if big.any() else ex / sh
    r_b = ex[big] / bf[big] if big.any() else ex / bf
    N.add("BenchRatioSharpMin", f"{np.nanmin(r_s):.0f}", "Section 7.4", src)
    N.add("BenchRatioSharpMax", f"{np.nanmax(r_s):.0f}", "Section 7.4", src)
    N.add("BenchRatioBFMin", f"{np.nanmin(r_b):.0f}", "Section 7.4", src)
    N.add("BenchRatioBFMax", f"{np.nanmax(r_b):.0f}", "Section 7.4", src)
    N.add("BenchRatioFromN", int(n[o][big][0]) if big.any() else int(n.min()), "Section 7.4", src)


