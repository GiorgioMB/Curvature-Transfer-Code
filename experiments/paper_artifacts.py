def bounds_numbers(N, rows, src):
    import compare_bounds as cb

    Rall = parse_bounds(rows)
    R = agg(Rall)
    G = len(R)
    N.add("NumGraphs", G, "Abstract; (C6); Section 6.1 (graphs in the aggregates)", src)
    N.add("NumGraphsAll", len(Rall), "Section 6 (all graphs in the tables)", src)
    for grp, lab in (("random", "NumRandom"), ("canonical", "NumCanonical"), ("real", "NumReal")):
        N.add(lab, sum(o["group"] == grp for o in Rall), "Section 6", src)
    N.add("CanonicalList", join(disp(o["graph"]) for o in Rall if o["group"] == "canonical"), "Section 6", src)
    _range(N, R, "lo_tighter", "LoTighter", "Abstract; Section 6.1 (Lower Bounds)", src)
    gain = [o["lo_relgain"] for o in R if fin(o["lo_relgain"])]
    N.add("GapRedMedian", pct(float(np.median(gain))) if gain else "--", "Abstract; Section 6.1", src)
    N.add("GapRedCount", len(gain), "Section 6.1 (graphs where the reduction is defined)", src)
    _range(N, R, "lo_relgain", "GapRed", "Section 6.1", src)
    N.add("MaxViolation", f"{max(o['max_violation'] for o in Rall):.1e}", "Section 6 (largest rounding excess)", src)
    bup = {o["graph"]: min(o["gap_up_JL"], o["gap_up_TLW"]) for o in R}
    N.add("UpBetterCount", sum(o["gap_up_ours"] < bup[o["graph"]] for o in R), "Section 6.1 (Upper Bounds)", src)
    N.add("UpLooserList", join(disp(o["graph"]) for o in R if o["gap_up_ours"] > bup[o["graph"]]), "Section 6.1", src)
    N.add("UpMaxExcess", f"{max([0.0] + [o['gap_up_ours'] - bup[o['graph']] for o in R]):.3f}", "Section 6.1", src)
    N.add("UpHalvedCount", sum(1 for o in R if o["gap_up_ours"] <= 0.5 * o["gap_up_JL"] and o["gap_up_JL"] > 0),
          "Section 6.1", src)
    N.add("LazyPriorBetterCount", sum(o["gap_Lup_prior"] < o["gap_Lup_ours"] for o in R), "Section 6.1", src)
    N.add("LazyEnvTighterMax", pct(max(o["Lup_tighter"] for o in R)) if R else "--", "Section 6.1", src)
    # sign certification: compared at display precision, so that the text agrees with the table
    more = [o for o in R if float(pct(o["cert_ours"])) > float(pct(o["cert_prior"]))]
    equal = [o for o in R if pct(o["cert_ours"]) == pct(o["cert_prior"])]
    N.add("CertMoreCount", len(more), "Section 6.1 (Sign Certification)", src)
    N.add("CertEqualCount", len(equal), "Section 6.1", src)
    N.add("CertMajorityCount", sum(o["cert_ours"] > 0.5 for o in R), "Abstract; Section 6.1", src)
    top = sorted(more, key=lambda o: o["cert_ours"] - o["cert_prior"], reverse=True)[:3]
    N.add("CertTopGains", join(f"{disp(o['graph'])} (from {pct(o['cert_prior'])}\\% to {pct(o['cert_ours'])}\\%)"
                               for o in top), "Section 6.1", src)
    r2 = lambda x: round(x, 2) if fin(x) else None
    rho_ok = [o for o in R if fin(o["rho_mid"]) and fin(o["rho_best_other"])]
    N.add("SpearmanCount", len(rho_ok), "Section 6.1 (graphs with a defined Spearman correlation)", src)
    N.add("SpearmanBestCount", sum(r2(o["rho_mid"]) >= r2(o["rho_best_other"]) for o in rho_ok), "Section 6.1 (Ranking)", src)
    top = [o for o in sorted(rho_ok, key=lambda o: o["rho_mid"] - o["rho_best_other"], reverse=True)
           if r2(o["rho_mid"]) > r2(o["rho_best_other"])][:3]
    N.add("SpearmanTopGains", join(f"{disp(o['graph'])} (from {o['rho_best_other']:.2f} to {o['rho_mid']:.2f})" for o in top),
          "Section 6.1", src)
    recs = ["rec_BF", "rec_ORCA", "rec_midprior", "rec_mid"]
    best = [o for o in R if all(fin(o[k]) for k in recs) and r2(o["rec_mid"]) >= max(r2(o[k]) for k in recs)]
    N.add("RecallOursBestCount", len(best), "Section 6.1", src)
    N.add("RecallCount", sum(1 for o in R if all(fin(o[k]) for k in recs)), "Section 6.1 (graphs with a defined recall)", src)
    _range(N, R, "frac_Bdef_nonneg", "Bdef", "Remark 5.2", src, with_graphs=False)
    _range(N, R, "corC2_first_tighter", "CorFirstTighter", "Appendix C (after Corollary C.2)", src, with_graphs=False)
    # Section 6.2: the graphs of the distribution figures (same per-edge arrays as the figures)
    by = {o["graph"]: o for o in Rall}
    for lab, name in suite.DIST_GRAPHS.items():
        if name in by:
            N.add(f"FigEdges:{lab}", thou(by[name]["E"]), "Section 6.2, Figure 3", src)
            N.add(f"FigBdef:{lab}", pct(by[name]["frac_Bdef_nonneg"]), "Section 6.2, Figure 3", src)
    labels = ("bound-comparison", "bound-comparison-lazy", "ranking", "bf-interval")
    return {lab: cb.grouped_rows(Rall, k) for k, lab in enumerate(labels)}


# ----------------------------------------------------------- screening
def screening_benchmark_numbers(N, rows, src):
    """Section 6.3, registry graphs: transport problems avoided for {c_OR < 0} with the stored intervals."""
    A = [r for r in rows if r.get("group") in suite.AGGREGATE_GROUPS]
    where = "Section 6.3 (graphs of Section 6.1, stored intervals)"
    for col, label in (("sign_avoided_sharpened", "ScreenBenchSignSharp"), ("sign_avoided_bf", "ScreenBenchSignBF")):
        v = [num(r, col) for r in A if fin(num(r, col))]
        if not v:
            continue
        N.add(f"{label}Min", pct(min(v)), where, src)
        N.add(f"{label}Max", pct(max(v)), where, src)


def _sci(x):
    if not fin(x):
        return "--"
    if x >= 100:
        return f"{x:.0f}"
    return f"{x:.2g}" if x < 1 else f"{x:.1f}"


def screening_large_numbers(N, rows, src):
    """Table 7 and the numbers of Section 6.3 on the large real networks, for the query {c_OR < 0}."""
    where = "Section 6.3 and Table 7 (large real networks, timed)"
    if not rows:
        return None
    E = [int(num(r, "E")) for r in rows]
    N.add("ScreenLargeCount", len(rows), "Abstract; Section 6.3", src)
    N.add("ScreenLargeMinEdges", thou(min(E)), where, src)
    N.add("ScreenLargeMaxEdges", thou(max(E)), "Abstract; Section 6.3", src)
    sp = lambda x: f"{x:.1f}" if fin(x) else "--"

    def mm(pairs, label, fmt, median=False, graphs=False):
        vals = [(v, g) for v, g in pairs if fin(v)]
        if not vals:
            return
        lo, hi = min(v for v, _ in vals), max(v for v, _ in vals)
        N.add(f"{label}Min", fmt(lo), where, src)
        N.add(f"{label}Max", fmt(hi), where, src)
        if graphs:
            N.add(f"{label}MinGraph", join(g for v, g in vals if fmt(v) == fmt(lo)), where, src)
            N.add(f"{label}MaxGraph", join(g for v, g in vals if fmt(v) == fmt(hi)), where, src)
        if median:
            N.add(f"{label}Median", fmt(float(np.median([v for v, _ in vals]))), where, src)

    g = [r["graph"] for r in rows]
    share = lambda r, k: num(r, k) / max(1.0, num(r, "E"))
    mm(zip([num(r, "sign_avoided") for r in rows], g), "ScreenSignAvoid", pct, graphs=True)
    mm(zip([num(r, "sign_speedup") for r in rows], g), "ScreenSignSpeedup", sp, median=True, graphs=True)
    # Work ratio: transport problems of exact evaluation per problem that certify-then-solve still solves.
    # It depends only on the decisions (deterministic), not on the speed of the solver.
    mm(zip([num(r, "E") / max(1.0, num(r, "sign_n_solved")) for r in rows], g), "ScreenSignWorkRatio", sp,
       median=True, graphs=True)
    mm(zip([share(r, "sign_n_bf") for r in rows], g), "ScreenSignShareBF", pct)
    mm(zip([share(r, "sign_n_tlw") for r in rows], g), "ScreenSignShareTLW", pct)
    st1 = [num(r, "sign_time_stage1") / num(r, "time_exact") for r in rows
           if fin(num(r, "sign_time_stage1")) and num(r, "time_exact") > 0]
    if st1:
        N.add("ScreenStageOneShareMax", pct(max(st1)), "Section 6.3 (first stage, as a share of exact evaluation)", src)
    threads = sorted({str(int(num(r, "threads"))) for r in rows if fin(num(r, "threads"))}, key=int)
    N.add("ScreenThreads", join(threads), "Section 6.3", src)
    lines = []
    for r in rows:
        M = max(1.0, num(r, "E"))
        lines.append(f"{r['graph']} & {thou(num(r, 'E'))} & {thou(num(r, 'max_deg'))} & {_sci(num(r, 'time_exact'))} & "
                     f"{pct(num(r, 'sign_n_bf') / M)} & {pct(num(r, 'sign_avoided'))} & {sp(num(r, 'sign_speedup'))} \\\\")
    return "\n".join(lines) + "\n"


