def key_of(name):
    return re.sub(r"[^A-Za-z0-9.]+", "-", name).strip("-")


def disp(name):
    return DISPLAY.get(name, name)


def join(items):
    items = list(items)
    if not items:
        return "none"
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + (", and " if len(items) > 2 else " and ") + items[-1]


class Numbers:
    def __init__(self):
        self.vals = OrderedDict()

    def add(self, key, value, where, source):
        self.vals[key] = (str(value), where, source)

    def tex(self, rows=None):
        out = ["% Generated by experiments/paper_artifacts.py -- do not edit by hand.",
               "% \\res{Key} prints a number; \\resrows{key} the body rows of a table."]
        for k, (v, _, _) in self.vals.items():
            out.append(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}")
        for k, txt in (rows or {}).items():
            out.append(f"\\expandafter\\def\\csname resrows@{k}\\endcsname{{%\n{txt.rstrip()}\n}}")
        return "\n".join(out) + "\n"


def pct(x):
    return f"{100 * x:.1f}"


def read_csv(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def num(r, k):
    try:
        return float(r[k])
    except (KeyError, ValueError, TypeError):
        return float("nan")


