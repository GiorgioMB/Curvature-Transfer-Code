def build(results_dir, paper_dir):
    gen = os.path.join(paper_dir, "generated")
    os.makedirs(gen, exist_ok=True)
    N = Numbers()
    rows = {}
    status = {}
    p = os.path.join(results_dir, "tables", "bounds", "bound_comparison.csv")
    if os.path.exists(p):
        rows.update(bounds_numbers(N, read_csv(p), os.path.relpath(p, results_dir)))
    p = os.path.join(results_dir, "tables", "screening", "screening.csv")
    if os.path.exists(p):
        rows["screening"] = screening_numbers(N, read_csv(p), os.path.relpath(p, results_dir))
    bdir = os.path.join(results_dir, "benchmark")
    if os.path.isdir(bdir):
        cands = sorted(f for f in os.listdir(bdir) if f.startswith("benchmark_ER_") and f.endswith(".csv"))
        if cands:
            p = os.path.join(bdir, cands[-1])
            benchmark_numbers(N, read_csv(p), os.path.relpath(p, results_dir))
    rdir = os.path.join(results_dir, "runs", "paper")
    if os.path.isdir(rdir):
        distribution_numbers(N, rdir)
    p = os.path.join(results_dir, "gnn", "gnn_results.json")
    cfgp = os.path.join(results_dir, "gnn", "config.json")
    if os.path.exists(p):
        cfg = json.load(open(cfgp)) if os.path.exists(cfgp) else {}
        rows["gnn_downstream"], rows["time_and_connectivity"], rows["gnn_tests"] = gnn_rows(N, json.load(open(p)), cfg, "gnn/gnn_results.json")
    allrows = {}
    for lab, ncols, where, step in TABLES:
        txt = rows.get(lab)
        status[lab] = "generated" if txt else f"MISSING (run step '{step}')"
        key = lab.replace("_", "-")
        allrows[key] = txt or pending_rows(ncols, lab.replace("_", "\\_"))
        open(os.path.join(gen, f"rows-{key}.tex"), "w").write(allrows[key])
    open(os.path.join(gen, "numbers.tex"), "w").write(N.tex(allrows))
    # ------------------------------------------------------------ index
    L = ["# What goes where", "",
         "Everything in this folder is generated by `python main.py`; nothing here is edited by hand.",
         "The manuscript (`../manuscript.tex`) reads `numbers.tex`, which holds every number and every table body;\nthe `rows-*.tex` files are the same table bodies, one file per table, for reading. A number that has not been",
         "generated is printed in red as `[Key]` in the PDF.", "",
         "## Tables (body rows; captions and headers are in the manuscript)", "",
         "| Table in the paper | LaTeX label | File | Status |", "| --- | --- | --- | --- |"]
    for lab, _, where, _ in TABLES:
        L.append(f"| {where} | `tab:{lab}` | `rows-{lab.replace('_', '-')}.tex` | {status[lab]} |")
    L += ["", "## Numbers in the text (`numbers.tex`, used as `\\res{Key}`)", "",
          "| Key | Value | Where it appears | Computed from (under results/) |", "| --- | --- | --- | --- |"]
    for k, (v, where, src) in N.vals.items():
        L.append(f"| `{k}` | {v} | {where} | `{src}` |")
    L += ["", "## Figures", "", "All figures are in `../figures_paper/` under the file names that the manuscript includes."]
    open(os.path.join(gen, "INDEX.md"), "w").write("\n".join(L) + "\n")
    return status, N


